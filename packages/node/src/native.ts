import { PolyglotError } from './errors.js';

interface NativeBinding {
  inspectNative(data: Buffer, maxInputBytes: number, maxDecodedBytes: number): Promise<string>;
  validateNative(data: Buffer, formats: string[], maxInputBytes: number, maxDecodedBytes: number): Promise<string>;
  nativeFormats(): string[];
  checkCompatibilityNative(formats: string[], strategy: string): Promise<string>;
  createNative(inputs: { format: string; data: Buffer; label?: string }[], strategy: string, validate: boolean, maxInputBytes: number, maxDecodedBytes: number, maxOutputBytes: number): Promise<{ data: Buffer; reportJson: string }>;
  strategiesNative(): string;
}

let binding: NativeBinding | undefined;

export function native(): NativeBinding {
  if (binding) return binding;
  try {
    // Generated by napi-rs. Kept separate from the stable public TypeScript API.
    binding = require('../native/index.js') as NativeBinding;
    return binding;
  } catch (cause) {
    throw new PolyglotError(
      'ERR_NATIVE_UNAVAILABLE',
      'Cannot load the polyglot-rs native addon for this platform. Build from source with npm run build at the workspace root.',
      { cause },
    );
  }
}
